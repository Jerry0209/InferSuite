#!/usr/bin/env python3
"""extract_cmd.py <rundir> <outdir> — pull the ref command line(s) and env out of a
SPEC run directory so the benchmark can be executed DIRECTLY inside the measurement
fence, with nothing else in the cgroup.

Two sources, each used for what it is authoritative about:
  * `specinvoke -n` in the run dir  -> the exact shell command line(s), redirects
    already attached (the config sets command_add_redirect = 1). This is SPEC's own
    documented dry-run output, so we are not reimplementing its quoting rules.
  * speccmds.cmd `-E VAR value`     -> the environment specinvoke would have set,
    including the OMP_NUM_THREADS / OMP_THREAD_LIMIT that enforce threads = 1.

Writes to <outdir>:
  speccmds_all.txt  every ref command line found (provenance: the PI's rule is to run
                    exactly ONE of them, so the discarded ones must stay on record)
  env.sh            shell-quoted `export` lines
  n_cmds            how many command lines the benchmark has

Prints the number of command lines on stdout.
"""
import os
import shlex
import subprocess
import sys


def specinvoke_cmds(rundir: str) -> list[str]:
    spec = os.environ.get("SPEC_ROOT") or os.environ["SPEC"]
    out = subprocess.run(
        [os.path.join(spec, "bin", "specinvoke"), "-n"],
        cwd=rundir, capture_output=True, text=True, check=True,
    ).stdout
    cmds = []
    for line in out.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        cmds.append(s)
    return cmds


def speccmds_env(rundir: str) -> list[tuple[str, str]]:
    """Parse the `-E NAME value` prologue of speccmds.cmd.

    Values may be single-quoted by SPEC when they contain spaces; shlex handles both
    forms. Lines stop mattering once the first non -E directive appears.
    """
    env = []
    path = os.path.join(rundir, "speccmds.cmd")
    with open(path) as f:
        for line in f:
            if not line.startswith("-E "):
                continue
            try:
                parts = shlex.split(line.strip())
            except ValueError:
                continue
            if len(parts) >= 2 and parts[0] == "-E":
                env.append((parts[1], parts[2] if len(parts) > 2 else ""))
    return env


# Session noise that SPEC captured from whoever happened to run --action=setup. It is
# not part of the benchmark's definition and carrying it into the measured process
# just makes episodes differ by who set them up.
DROP_PREFIXES = (
    "CLAUDE", "VSCODE", "COPILOT", "SSH_", "TERM", "XDG_", "DBUS", "GIT_",
    "LS_COLORS", "COLORTERM", "BROWSER", "DEBUGINFOD", "_CE_", "CONDA", "_CONDA",
    "KUBECONFIG", "AI_AGENT", "BUILD_NCPUS", "BUILD_SLOTS", "CFG_NAME", "INFRA",
    "PERF", "SPEC_LABEL", "SPEC_ROOT", "OLDPWD", "XML_CATALOG_FILES",
    "NoDefaultCurrentDirectoryInExePath", "COREPACK",
)


def main() -> int:
    rundir, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)

    cmds = specinvoke_cmds(rundir)
    with open(os.path.join(outdir, "speccmds_all.txt"), "w") as f:
        for c in cmds:
            f.write(c + "\n")

    kept, dropped = [], []
    for name, val in speccmds_env(rundir):
        (dropped if name.startswith(DROP_PREFIXES) else kept).append((name, val))

    with open(os.path.join(outdir, "env.sh"), "w") as f:
        f.write("# generated by extract_cmd.py — environment specinvoke would set\n")
        for name, val in kept:
            f.write(f"export {name}={shlex.quote(val)}\n")
        f.write(f"\n# dropped as session noise, not benchmark definition: "
                f"{' '.join(n for n, _ in dropped)}\n")

    with open(os.path.join(outdir, "n_cmds"), "w") as f:
        f.write(f"{len(cmds)}\n")

    print(len(cmds))
    return 0


if __name__ == "__main__":
    sys.exit(main())
